<?php

namespace Modules\PMB\Services;

use Modules\Core\Helpers\ManagementService;
use Modules\PMB\Models\LogODS;

class LogODSManagementService
{
    /**
     * @var LogODS
     */
    protected $model = LogODS::class;

    /**
     * Init service.
     */
    public function __construct()
    {
        $this->model = new LogODS;
    }

    /**
     * Menampilkan list data
     *
     * @param int|null $page
     * @param int|null $perPage
     * @param array $order
     * @param array $filter
     *
     * @return mixed
     */
    public function index(int|null $page = null, int|null $perPage = null, array $order = [], array $filter = []): mixed
    {
        return ManagementService::create($this->model)->index($page, $perPage, $order, $filter);
    }

    /**
     * Menampilkan spesifik data berdasarkan id.
     *
     * @param int $id
     *
     * @return LogODS
     */
    public function show(int $id): LogODS
    {
        return $this->model->findOrFail($id);
    }

    /**
     * Buat data baru.
     *
     * @param array $data
     *
     * @return LogODS
     */
    public function store(array $data): LogODS
    {
        return $this->model->create($data);
    }

    /**
     * Update spesifik data berdasarkan id.
     *
     * @param array $data
     * @param int $id
     *
     * @return LogODS
     */
    public function update(array $data, int $id): LogODS
    {
        $model = $this->model->findOrFail($id);

        $model->update($data);

        return $model;
    }

    /**
     * Hapus spesifik data berdasarkan id.
     *
     * @param int $id
     *
     * @return void
     */
    public function destroy(int $id): void
    {
        $model = $this->model->findOrFail($id);

        $model->destroy($model->id);
    }
}
